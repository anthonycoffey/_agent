#!/usr/bin/env node
// Generate per-workflow Markdown "Node Reference" sections from the JSON files
// in agent/n8n/workflows/.
//
// Each existing doc claims one or more workflows via frontmatter:
//   ---
//   n8n_workflows: [bugsy-job-board-fetcher, bugsy-job-board-ui]
//   ---
// Workflows not claimed by any doc get a fresh stub at docs/workflows/<basename>.md.
//
// Inside the doc, the generated block is delimited by HTML-comment markers
// named for the workflow basename, so a single doc can hold multiple blocks:
//   <!-- NODE-REF:START:<basename> -->...<!-- NODE-REF:END:<basename> -->
// Anything outside the markers is left untouched.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const ROOT = path.resolve(path.dirname(__filename), '..', '..', '..');
const WORKFLOWS_DIR = path.join(ROOT, 'agent', 'n8n', 'workflows');
const DOCS_DIR = path.join(ROOT, 'docs', 'workflows');

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

const startMarker = (basename) =>
  `<!-- NODE-REF:START:${basename} — auto-generated by agent/n8n/scripts/generate-workflow-reference.mjs; do not edit by hand -->`;
const endMarker = (basename) => `<!-- NODE-REF:END:${basename} -->`;

function slug(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '') || 'node';
}

function escapePipe(s) {
  return String(s ?? '').replace(/\|/g, '\\|');
}

function fence(lang, body) {
  // Prevent the inner body from prematurely closing the fence by bumping the
  // fence length if the body contains triple backticks.
  let ticks = '```';
  while (body.includes(ticks)) ticks += '`';
  return `${ticks}${lang}\n${body}\n${ticks}`;
}

function readFrontmatter(content) {
  // CRLF-tolerant. On Windows checkouts (no .gitattributes) tracked .md files
  // arrive with CRLF, but Node-written files use LF — accept either so the
  // script doesn't mistake CRLF docs as having no frontmatter and spuriously
  // create stub copies. See BUG-DOCS-001.
  const m = content.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return { fm: {}, body: content, rawHead: '' };
  const fm = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z0-9_]+):\s*(.*)$/);
    if (!kv) continue;
    const [, k, v] = kv;
    const trimmedV = v.replace(/\s+$/, '');
    const arr = trimmedV.match(/^\[([^\]]*)\]$/);
    fm[k] = arr
      ? arr[1].split(',').map((x) => x.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean)
      : trimmedV.replace(/^['"]|['"]$/g, '');
  }
  return { fm, body: content.slice(m[0].length), rawHead: m[0] };
}

function listDocs() {
  if (!fs.existsSync(DOCS_DIR)) fs.mkdirSync(DOCS_DIR, { recursive: true });
  return fs
    .readdirSync(DOCS_DIR)
    .filter((f) => f.endsWith('.md'))
    .map((f) => path.join(DOCS_DIR, f));
}

function listWorkflows() {
  return fs
    .readdirSync(WORKFLOWS_DIR)
    .filter((f) => f.endsWith('.json'))
    .map((f) => ({
      basename: f.replace(/\.json$/, ''),
      path: path.join(WORKFLOWS_DIR, f),
    }));
}

// ---------------------------------------------------------------------------
// Node renderers
// ---------------------------------------------------------------------------

function renderWebhook(p) {
  return [
    `- **Method:** \`${p.httpMethod || 'GET'}\``,
    `- **Path:** \`/${p.path || ''}\``,
    p.responseMode ? `- **Response mode:** \`${p.responseMode}\`` : null,
  ]
    .filter(Boolean)
    .join('\n');
}

function renderScheduleTrigger(p) {
  const rules = (p.rule?.interval || []).map((r) => {
    if (r.field === 'cronExpression') return `cron \`${r.expression}\``;
    return Object.entries(r).map(([k, v]) => `${k}=${v}`).join(', ');
  });
  return [
    rules.length ? `- **Schedule:** ${rules.join(', ')}` : null,
    p.timezone ? `- **Timezone:** \`${p.timezone}\`` : null,
  ]
    .filter(Boolean)
    .join('\n');
}

function renderCode(p) {
  const lang = p.language === 'python' ? 'python' : 'javascript';
  return fence(lang, p.jsCode || p.pythonCode || '');
}

function renderHttpRequest(p) {
  const lines = [
    `- **Method:** \`${p.method || 'GET'}\``,
    `- **URL:** \`${p.url || ''}\``,
  ];
  if (p.authentication && p.authentication !== 'none')
    lines.push(`- **Auth:** \`${p.authentication}\`${p.genericAuthType ? ` (${p.genericAuthType})` : ''}`);
  if (p.options?.timeout) lines.push(`- **Timeout:** ${p.options.timeout}ms`);

  if (p.sendHeaders && p.headerParameters?.parameters?.length) {
    lines.push('', '**Headers:**');
    for (const h of p.headerParameters.parameters)
      lines.push(`- \`${h.name}\`: \`${h.value}\``);
  }
  if (p.sendBody) {
    lines.push('', '**Body:**');
    if (p.specifyBody === 'json' && p.jsonBody)
      lines.push(fence('json', p.jsonBody));
    else if (p.bodyParameters?.parameters?.length) {
      for (const b of p.bodyParameters.parameters)
        lines.push(`- \`${b.name}\`: \`${b.value}\``);
    } else if (p.body) lines.push(fence('text', String(p.body)));
  }
  return lines.join('\n');
}

function renderSet(p) {
  const items = p.assignments?.assignments || [];
  if (!items.length) return '_(no assignments)_';
  return items
    .map((a) => `- \`${a.name}\` = \`${a.value}\`${a.type ? ` *(${a.type})*` : ''}`)
    .join('\n');
}

function renderIf(p) {
  const conds = p.conditions?.conditions || p.conditions || [];
  const combinator = p.conditions?.combinator || 'and';
  const list = Array.isArray(conds) ? conds : [];
  if (!list.length) return fence('json', JSON.stringify(p.conditions, null, 2));
  return [
    `*Combinator:* \`${combinator}\``,
    '',
    ...list.map((c) => {
      const left = c.leftValue ?? c.value1 ?? '';
      const right = c.rightValue ?? c.value2 ?? '';
      const op = c.operator?.operation || c.operation || '?';
      return `- \`${left}\` **${op}** \`${right}\``;
    }),
  ].join('\n');
}

function renderPostgres(p) {
  const parts = [`- **Operation:** \`${p.operation || 'executeQuery'}\``];
  if (p.query) parts.push('', '**Query:**', fence('sql', p.query));
  if (p.table) parts.push(`- **Table:** \`${p.table}\``);
  return parts.join('\n');
}

function renderRespondToWebhook(p) {
  const lines = [`- **Respond with:** \`${p.respondWith || 'text'}\``];
  if (p.responseCode) lines.push(`- **Status code:** \`${p.responseCode}\``);
  if (p.responseBody) {
    lines.push('', '**Body:**');
    lines.push(fence(p.respondWith === 'json' ? 'json' : 'text', String(p.responseBody)));
  }
  return lines.join('\n');
}

function renderLangchainOpenAi(p) {
  const lines = [];
  const model = p.modelId?.value || p.model || '?';
  lines.push(`- **Model:** \`${model}\``);
  if (p.options?.temperature != null) lines.push(`- **Temperature:** \`${p.options.temperature}\``);
  if (p.options?.maxTokens != null) lines.push(`- **Max tokens:** \`${p.options.maxTokens}\``);
  const msgs = p.messages?.values || p.messages?.messageValues || [];
  for (const m of msgs) {
    lines.push('', `**${(m.role || 'user').toUpperCase()} message:**`);
    lines.push(fence('text', String(m.content || '')));
  }
  return lines.join('\n');
}

function renderLangchainAgent(p) {
  const lines = [];
  if (p.promptType) lines.push(`- **Prompt type:** \`${p.promptType}\``);
  if (p.text) {
    lines.push('', '**Prompt:**');
    lines.push(fence('text', String(p.text)));
  }
  if (p.options?.systemMessage) {
    lines.push('', '**System message:**');
    lines.push(fence('text', String(p.options.systemMessage)));
  }
  return lines.join('\n');
}

function renderLangchainLm(p) {
  return [
    `- **Model:** \`${p.model?.value || p.modelId?.value || p.model || '?'}\``,
    p.options?.temperature != null ? `- **Temperature:** \`${p.options.temperature}\`` : null,
  ]
    .filter(Boolean)
    .join('\n');
}

function renderLangchainMemory(p) {
  return [
    p.tableName ? `- **Table:** \`${p.tableName}\`` : null,
    p.sessionKey ? `- **Session key:** \`${p.sessionKey}\`` : null,
    p.contextWindowLength != null ? `- **Context window:** \`${p.contextWindowLength}\`` : null,
  ]
    .filter(Boolean)
    .join('\n');
}

function fmtResourceLocator(loc) {
  if (loc == null) return null;
  if (typeof loc === 'string') return loc;
  if (loc.cachedResultName && loc.value) return `${loc.cachedResultName} (${loc.value})`;
  return loc.value || loc.cachedResultName || null;
}

function renderSlack(p) {
  const lines = [`- **Resource:** \`${p.resource || 'message'}\``, `- **Operation:** \`${p.operation || 'post'}\``];
  const ch = fmtResourceLocator(p.channel) || fmtResourceLocator(p.channelId) || fmtResourceLocator(p.user);
  if (ch) lines.push(`- **Channel:** \`${ch}\``);
  if (p.text) {
    lines.push('', '**Text:**');
    lines.push(fence('text', String(p.text)));
  }
  return lines.join('\n');
}

function renderGmail(p) {
  const lines = [
    `- **Resource:** \`${p.resource || 'message'}\``,
    `- **Operation:** \`${p.operation || 'send'}\``,
  ];
  if (p.to) lines.push(`- **To:** \`${p.to}\``);
  if (p.subject) lines.push(`- **Subject:** \`${p.subject}\``);
  if (p.message || p.body) {
    lines.push('', '**Message:**');
    lines.push(fence('text', String(p.message || p.body)));
  }
  return lines.join('\n');
}

function renderGmailTrigger(p) {
  return [
    p.event ? `- **Event:** \`${p.event}\`` : null,
    p.pollTimes?.item?.length
      ? `- **Poll:** ${p.pollTimes.item.map((t) => JSON.stringify(t)).join(', ')}`
      : null,
    p.filters ? '\n**Filters:**\n' + fence('json', JSON.stringify(p.filters, null, 2)) : null,
  ]
    .filter(Boolean)
    .join('\n');
}

function renderUnknown(p) {
  // Fall back to a JSON dump of the params (minus secrets).
  return fence('json', JSON.stringify(p, null, 2));
}

const RENDERERS = {
  'n8n-nodes-base.webhook': renderWebhook,
  'n8n-nodes-base.scheduleTrigger': renderScheduleTrigger,
  'n8n-nodes-base.code': renderCode,
  'n8n-nodes-base.set': renderSet,
  'n8n-nodes-base.if': renderIf,
  'n8n-nodes-base.httpRequest': renderHttpRequest,
  'n8n-nodes-base.postgres': renderPostgres,
  'n8n-nodes-base.respondToWebhook': renderRespondToWebhook,
  'n8n-nodes-base.slack': renderSlack,
  'n8n-nodes-base.gmail': renderGmail,
  'n8n-nodes-base.gmailTrigger': renderGmailTrigger,
  '@n8n/n8n-nodes-langchain.openAi': renderLangchainOpenAi,
  '@n8n/n8n-nodes-langchain.agent': renderLangchainAgent,
  '@n8n/n8n-nodes-langchain.lmChatOpenAi': renderLangchainLm,
  '@n8n/n8n-nodes-langchain.memoryPostgresChat': renderLangchainMemory,
};

function renderNode(node) {
  const renderer = RENDERERS[node.type] || renderUnknown;
  const detail = renderer(node.parameters || {});
  const credLines = [];
  if (node.credentials) {
    for (const [k, v] of Object.entries(node.credentials)) {
      credLines.push(`- **Credential (${k}):** \`${v.name || v.id || '?'}\``);
    }
  }
  if (node.onError) credLines.push(`- **On error:** \`${node.onError}\``);
  return [
    `#### ${node.name}`,
    `*Type:* \`${node.type}\``,
    '',
    detail || '_(no parameters)_',
    credLines.length ? '\n' + credLines.join('\n') : '',
  ]
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd();
}

// ---------------------------------------------------------------------------
// Mermaid flow
// ---------------------------------------------------------------------------

function renderFlow(workflow) {
  const nodeIds = new Map();
  for (const n of workflow.nodes) nodeIds.set(n.name, slug(n.name));

  const edges = [];
  for (const [from, outputs] of Object.entries(workflow.connections || {})) {
    for (const [outType, targets] of Object.entries(outputs)) {
      for (const targetList of targets || []) {
        for (const t of targetList || []) {
          const fromId = nodeIds.get(from);
          const toId = nodeIds.get(t.node);
          if (!fromId || !toId) continue;
          const label = outType === 'main' ? '' : `|${outType}|`;
          edges.push(`  ${fromId} -->${label} ${toId}`);
        }
      }
    }
  }

  const nodeLines = workflow.nodes.map((n) => `  ${nodeIds.get(n.name)}["${escapePipe(n.name)}"]`);
  return fence('mermaid', ['flowchart TD', ...nodeLines, ...edges].join('\n'));
}

// ---------------------------------------------------------------------------
// Block assembly
// ---------------------------------------------------------------------------

function renderBlock(basename, workflow) {
  const generatedAt = new Date().toISOString().slice(0, 10);
  const head = [
    startMarker(basename),
    '',
    `## Node reference: ${workflow.name || basename}`,
    '',
    `> Auto-generated from \`agent/n8n/workflows/${basename}.json\` on ${generatedAt}. Run \`node agent/n8n/scripts/generate-workflow-reference.mjs\` to refresh.`,
    '',
    `**Active:** \`${workflow.active ?? false}\` · **Nodes:** ${workflow.nodes.length}${
      workflow.settings?.executionOrder ? ` · **Execution order:** \`${workflow.settings.executionOrder}\`` : ''
    }`,
    '',
    '### Flow',
    '',
    renderFlow(workflow),
    '',
    '### Nodes',
    '',
  ];
  const nodeBlocks = workflow.nodes.map(renderNode).join('\n\n');
  return [...head, nodeBlocks, '', endMarker(basename)].join('\n');
}

// ---------------------------------------------------------------------------
// Doc-side: find owner, insert/replace block
// ---------------------------------------------------------------------------

function buildOwnership(docs) {
  // Map: workflow basename → { docPath, fm, body }
  const owners = new Map();
  for (const docPath of docs) {
    const content = fs.readFileSync(docPath, 'utf8');
    const { fm, body } = readFrontmatter(content);
    const claimed = Array.isArray(fm.n8n_workflows) ? fm.n8n_workflows : [];
    for (const w of claimed) owners.set(w, { docPath, fm, body, content });
  }
  return owners;
}

function insertOrReplace(content, basename, block) {
  const startRe = new RegExp(
    `<!-- NODE-REF:START:${basename}[^>]*-->[\\s\\S]*?<!-- NODE-REF:END:${basename} -->`,
    'm',
  );
  if (startRe.test(content)) {
    return content.replace(startRe, block);
  }
  // Append at the end with a separator.
  const sep = content.endsWith('\n') ? '\n' : '\n\n';
  return content + sep + block + '\n';
}

function stubDocFor(basename, workflow) {
  const title = workflow.name || basename;
  return [
    '---',
    `title: ${title}`,
    `tags: [bugsy, n8n, workflow]`,
    `n8n_workflows: [${basename}]`,
    '---',
    '',
    `# ${title}`,
    '',
    `\`agent/n8n/workflows/${basename}.json\`.`,
    '',
    '_Add a hand-written summary of what this workflow does and why._',
    '',
  ].join('\n');
}

function ensureWorkflowClaim(content, basename) {
  // If the doc has frontmatter but is missing this basename in n8n_workflows, add it.
  const { fm } = readFrontmatter(content);
  const current = Array.isArray(fm.n8n_workflows) ? fm.n8n_workflows : [];
  if (current.includes(basename)) return content;
  const next = [...current, basename];
  const replacement = `n8n_workflows: [${next.join(', ')}]`;
  if (/^n8n_workflows:.*$/m.test(content)) {
    return content.replace(/^n8n_workflows:.*$/m, replacement);
  }
  // Insert before the closing frontmatter fence.
  return content.replace(/^(---\n[\s\S]*?)(\n---\n)/, `$1\n${replacement}$2`);
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main() {
  const workflows = listWorkflows();
  const docs = listDocs();
  const owners = buildOwnership(docs);

  const summary = [];
  for (const { basename, path: wfPath } of workflows) {
    const workflow = JSON.parse(fs.readFileSync(wfPath, 'utf8'));
    const block = renderBlock(basename, workflow);

    let docPath, content;
    const owner = owners.get(basename);
    if (owner) {
      docPath = owner.docPath;
      // Re-read so we pick up any block written earlier this run by a sibling workflow.
      content = fs.readFileSync(docPath, 'utf8');
    } else {
      docPath = path.join(DOCS_DIR, `${basename}.md`);
      if (fs.existsSync(docPath)) {
        content = fs.readFileSync(docPath, 'utf8');
        content = ensureWorkflowClaim(content, basename);
      } else {
        content = stubDocFor(basename, workflow);
      }
    }

    const next = insertOrReplace(content, basename, block);
    fs.writeFileSync(docPath, next);
    summary.push(`  ${basename.padEnd(32)} -> ${path.relative(ROOT, docPath)}`);
  }

  console.log(`Generated node-reference blocks for ${workflows.length} workflow(s):`);
  console.log(summary.join('\n'));
}

main();
